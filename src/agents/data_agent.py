# LLM mode
# ---------------------------------------------------------------------------
SYSTEM = f"""You are the Data Agent in a research system about the India NFHS-5 (DHS 2019-21) Individual Recode: 724,115 women aged 15-49.

Use tools for everything:
- Definitions and relevant variables: search_documentation / lookup_variable. Never guess what a variable means from its name.
- Every number: weighted_percentage, count_respondents, age_standardized_rates, rank_underserved_groups, channel_reach, or run_sql. Never compute or estimate numbers yourself.
- Percentages are weighted (w = v005 / 1,000,000). Report unweighted n with them and mention reliability flags.
- Employment, mobile phone, bank and internet questions exist only for state-module women (about 15%); say so when relevant.
- If the task needs a target population for outreach, identify it with tools and then call set_target_population with numeric-code filters.
- Say clearly what is a data result and what is your interpretation. Do not claim causation.

Derived indicators (name: rule): {json.dumps({d.name: d.rule for d in DERIVED_BY_NAME.values()})}
Grouping columns: {json.dumps(GROUPING_COLUMNS)}
Use numeric codes in filters (look up codes with lookup_variable; e.g. v025: 1 urban, 2 rural)."""


def run_llm(task, trace, llm, needs_population=False):
    report = DataReport()

    def set_target_population(trace, description, filters):
        report.population = build_profile(filters, trace, description)
        report.population_reason = "chosen by the Data Agent (LLM)"
        return {"ok": True, "population": report.population.to_dict()}

    tools = DATA_TOOLS + [Tool(
        "set_target_population",
        "Declare the population the outreach research should target (after identifying it with data tools).",
        {"type": "object", "properties": {"description": {"type": "string"},
                                          "filters": DATA_TOOLS_BY_NAME["weighted_percentage"].input_schema["properties"]["filters"]},
         "required": ["description", "filters"]},
        set_target_population, AGENT)]
    by_name = {t.name: t for t in tools}
    prompt = task + ("\n\nThis task needs a target population: finish by calling set_target_population."
                     if needs_population else "")
    messages = [{"role": "user", "content": prompt}]
    response = None
    for _ in range(MAX_TURNS):
        response = llm.create(system=SYSTEM, messages=messages, tools=[t.to_anthropic() for t in tools],
                              purpose="data agent")
        messages.append({"role": "assistant", "content": response.content})
        uses = [b for b in response.content if b.type == "tool_use"]
        if response.stop_reason != "tool_use" or not uses:
            break
        results = []
        for use in uses:
            trace.step(AGENT, "decided", use.name, detail="LLM chose this tool", inputs=use.input)
            output, error = by_name[use.name].run(trace, dict(use.input))
            if not error:
                # Facts come from the tool output (code), not from the model's text.
                for line in facts.facts_for_tool(use.name, output, use.input):
                    trace.say(DATA_FACT, line, [use.name])
            results.append({"type": "tool_result", "tool_use_id": use.id,
                            "content": tool_result_text(output), "is_error": error})
        messages.append({"role": "user", "content": results})
    report.summary = text_of(response) if response is not None else ""
    return report
